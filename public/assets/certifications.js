function filterAndRender() {
  const query = (searchInput?.value || "").trim().toLowerCase();

  filteredItems = certData.filter(item => {
    const matchCat = activeCategory === "all" || item.category === activeCategory;
    const matchText = !query || [
      item.title,
      item.categoryLabel,
      item.issuer,
      item.date,
      item.credId,
      item.highlight,
      item.desc,
      projectLinks[item.id]?.title || "",
      item.coAuthors || ""
    ].join(" ").toLowerCase().includes(query);
    return matchCat && matchText;
  });

  if (filteredItems.length === 0) {
    gridContainer.innerHTML = "";
    if (emptyEl) emptyEl.hidden = false;
  } else {
    if (emptyEl) emptyEl.hidden = true;
    gridContainer.innerHTML = filteredItems.map((item, idx) => renderCard(item, idx)).join("");
  }

  if (countEl) {
    countEl.textContent = `${filteredItems.length} item${filteredItems.length === 1 ? '' : 's'}`;
  }
}

// Lightbox modal logic & accessibility focus management
let lastFocusedElement = null;

function openModalById(id, trigger = null) {
  lastFocusedElement = trigger || document.activeElement;
  const index = filteredItems.findIndex(item => item.id === id);
  if (index !== -1) {
    showModalAtIndex(index);
  } else {
    const fallbackIdx = certData.findIndex(item => item.id === id);
    if (fallbackIdx !== -1) {
      filteredItems = [certData[fallbackIdx], ...filteredItems.filter(i => i.id !== id)];
      showModalAtIndex(0);
    }
  }
}

function showModalAtIndex(index) {
  if (index < 0 || index >= filteredItems.length) return;
  currentModalIndex = index;
  const item = filteredItems[index];

  modalImg.src = item.image;
  modalImg.alt = item.title;
  modalCategory.textContent = item.categoryLabel;
  modalCategory.className = `cert-pill cert-pill--${item.category}`;
  modalIssuer.textContent = item.issuer;
  modalDate.textContent = item.date;
  modalTitle.textContent = item.title;
  modalDesc.textContent = item.desc;

  if (item.credId) {
    modalCredWrap.hidden = false;
    modalCred.textContent = item.credId;
  } else {
    modalCredWrap.hidden = true;
  }

  const modalBtns = [];
  item.links.forEach(btn => {
    if (btn.action !== "modal") {
      modalBtns.push(`<a class="key key--sm ${btn.primary ? 'key--red' : 'key--outline'}" href="${btn.href}" ${btn.external ? 'target="_blank" rel="noopener"' : ''}>${btn.label}</a>`);
    }
  });
  modalBtns.push(`<a class="key key--sm key--outline" href="${item.image}" target="_blank" rel="noopener">Open High-Res Image ↗</a>`);
  modalActions.innerHTML = modalBtns.join("");

  modal.hidden = false;
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";

  setTimeout(() => {
    const closeBtn = n(".cert-modal__close");
    if (closeBtn) closeBtn.focus();
  }, 40);
}

function closeModal() {
  modal.hidden = true;
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  if (lastFocusedElement && typeof lastFocusedElement.focus === "function") {
    lastFocusedElement.focus();
  }
}

function nextModal() {
  const nextIdx = (currentModalIndex + 1) % filteredItems.length;
  showModalAtIndex(nextIdx);
}

function prevModal() {
  const prevIdx = (currentModalIndex - 1 + filteredItems.length) % filteredItems.length;
  showModalAtIndex(prevIdx);
}

// Event Listeners
chipsContainer.addEventListener("click", e => {
  const chip = e.target.closest("[data-category]");
  if (!chip) return;
  activeCategory = chip.dataset.category;
  L("[data-category]", chipsContainer).forEach(btn => {
    btn.setAttribute("aria-pressed", String(btn === chip));
  });
  filterAndRender();
});

searchInput?.addEventListener("input", filterAndRender);

// Click events for opening modal and buttons
document.addEventListener("click", e => {
  const openTrigger = e.target.closest("[data-open-modal]");
  if (openTrigger) {
    e.preventDefault();
    openModalById(openTrigger.dataset.openModal, openTrigger);
    return;
  }

  if (e.target.closest("[data-modal-close]")) {
    closeModal();
    return;
  }

  if (e.target.closest("[data-modal-prev]")) {
    prevModal();
    return;
  }

  if (e.target.closest("[data-modal-next]")) {
    nextModal();
    return;
  }
});

// Keyboard support
window.addEventListener("keydown", e => {
  if (modal.hidden) return;
  if (e.key === "Escape") closeModal();
  if (e.key === "ArrowRight") nextModal();
  if (e.key === "ArrowLeft") prevModal();
});

// Keep keyboard focus inside the certificate dialog.
modal.addEventListener("keydown", e => {
  if (e.key !== "Tab") return;
  const items = [...modal.querySelectorAll('button, a[href], [tabindex="0"]')].filter(el => !el.hidden && el.getClientRects().length);
  const first = items[0], last = items.at(-1);
  if (e.shiftKey && document.activeElement === first) { e.preventDefault(); last?.focus(); }
  else if (!e.shiftKey && document.activeElement === last) { e.preventDefault(); first?.focus(); }
});

